//-----------------------------------------------------------------------------
// usb_tx_serializer.v
//
// "Serializer 8:1 + EOP Gen" of the USB 2.0 PHY TX path (HS 480 / FS 12 /
// LS 1.5 Mbps).  Position in the datapath:
//
//   TX Holding -> SYNC/PID mux -> Bit Stuffer -> NRZI Encoder -> [THIS BLOCK]
//                                                                    |
//                                  AFE Interface (TX Data Boundary) -> Transmitter
//
// Clocking
//   * One clock only: clk_bit (480 MHz, PLL bit clock).
//   * The 60 MHz word interface is a clock ENABLE of clk_bit: ce60 is high for
//     exactly one clk_bit cycle out of eight, aligned with the clk60 rising
//     edge (generated by Clock/Reset Mgmt).  The upstream blocks run on clk60,
//     so in_valid / in_data / in_nbits / in_last are 8-cycle multicycle paths.
//     A word is transferred on a clk_bit edge where ce60 && in_valid && in_ready.
//
// Input words
//   * in_data is already NRZI-encoded (line level, J = 1, K = 0), LSB first.
//   * All words except the last one carry 8 valid bits (in_nbits is ignored).
//   * The last word of a packet (in_last = 1) carries in_nbits = 0..8 valid
//     bits (values > 8 are clamped to 8).  in_nbits = 0 with in_last = 1 sends
//     an EOP only (e.g. LS keep-alive).
//   * In HS a word must be presented every ce60 period to keep the line gapless;
//     otherwise the packet is terminated with an EOP and tx_underrun pulses.
//   * in_ready goes low from the acceptance of the last word until the EOP is
//     finished (tx_done), which guarantees a gap between packets.
//
// EOP generation (after the last data bit)
//   * HS    : 8 bit times at the inverted level of the last data bit
//             (NRZI 01111111 = one transition followed by seven held bits).
//   * FS/LS : SE0 for 2 bit times (tx_se0 = 1), then J for 1 bit time.
//   Afterwards tx_en is released and tx_done pulses for one cycle.
//
// Speed  (XcvrSelect encoding): 00 = HS, 01 = FS, 10 = LS, 11 = treated as FS
//   (LS-via-FS-preamble switching is not implemented).  speed is sampled when
//   a packet starts and is reported on tx_speed for the driver mode select.
//
// Outputs (registered, clk_bit domain): txd (J = 1 / K = 0), tx_en, tx_se0.
//   While tx_se0 = 1 the driver forces SE0 and txd is don't care.
//-----------------------------------------------------------------------------
`timescale 1ns/1ps

module usb_tx_serializer #(
    parameter FS_DIV = 40,    // clk_bit cycles per FS bit (480 MHz / 12 MHz)
    parameter LS_DIV = 320,   // clk_bit cycles per LS bit (480 MHz / 1.5 MHz)
    parameter DIV_W  = 9      // width of the bit-time counter (>= clog2(LS_DIV))
) (
    input  wire        clk_bit,      // 480 MHz bit clock
    input  wire        rst_n,        // async assert, release synchronized to clk_bit
    input  wire        ce60,         // 1 cycle in 8, aligned with clk60

    input  wire [1:0]  speed,        // 00 HS, 01 FS, 10 LS

    input  wire        in_valid,
    output wire        in_ready,
    input  wire [7:0]  in_data,      // NRZI-encoded bits, LSB first
    input  wire [3:0]  in_nbits,     // valid bits of the LAST word (0..8)
    input  wire        in_last,      // last word of the packet

    output reg         txd,          // line level: J = 1, K = 0
    output reg         tx_en,        // driver enable
    output reg         tx_se0,       // force SE0 (FS/LS EOP)
    output reg  [1:0]  tx_speed,     // speed of the current packet
    output wire        busy,
    output reg         tx_done,      // 1-cycle pulse at the end of a packet
    output reg         tx_underrun   // 1-cycle pulse: packet aborted by underrun
);

    localparam [1:0] SPD_HS = 2'b00;
    localparam [1:0] SPD_FS = 2'b01;
    localparam [1:0] SPD_LS = 2'b10;

    localparam [1:0] ST_IDLE = 2'd0;
    localparam [1:0] ST_RUN  = 2'd1;
    localparam [1:0] ST_EOP  = 2'd2;

    // one-word holding register (clk60 side)
    reg        hold_valid;
    reg [7:0]  hold_data;
    reg [3:0]  hold_nbits;
    reg        hold_last;
    reg        closing;          // last word accepted, packet not finished yet

    // output shifter
    reg [1:0]        st;
    reg [7:0]        cur_data;
    reg [3:0]        cur_cnt;    // bits left in cur_data
    reg              cur_last;
    reg [1:0]        spd_q;
    reg [DIV_W-1:0]  tick_cnt;
    reg [3:0]        eop_cnt;
    reg              last_line;  // level of the last transmitted data bit

    function [DIV_W-1:0] div_m1;
        input [1:0] spd;
        begin
            case (spd)
                SPD_HS:  div_m1 = {DIV_W{1'b0}};
                SPD_LS:  div_m1 = LS_DIV - 1;
                default: div_m1 = FS_DIV - 1;
            endcase
        end
    endfunction

    wire tick   = (tick_cnt == div_m1(spd_q));
    wire accept = ce60 & in_valid & in_ready;
    wire [3:0] nbits_eff = in_last ? ((in_nbits > 4'd8) ? 4'd8 : in_nbits) : 4'd8;

    assign in_ready = ~hold_valid & ~closing & (st != ST_EOP);
    assign busy     = hold_valid | (st != ST_IDLE);

    always @(posedge clk_bit or negedge rst_n) begin
        if (!rst_n) begin
            hold_valid  <= 1'b0;
            hold_data   <= 8'd0;
            hold_nbits  <= 4'd0;
            hold_last   <= 1'b0;
            closing     <= 1'b0;
            st          <= ST_IDLE;
            cur_data    <= 8'd0;
            cur_cnt     <= 4'd0;
            cur_last    <= 1'b0;
            spd_q       <= SPD_HS;
            tick_cnt    <= {DIV_W{1'b0}};
            eop_cnt     <= 4'd0;
            last_line   <= 1'b1;
            txd         <= 1'b1;
            tx_en       <= 1'b0;
            tx_se0      <= 1'b0;
            tx_speed    <= SPD_HS;
            tx_done     <= 1'b0;
            tx_underrun <= 1'b0;
        end else begin
            tx_done     <= 1'b0;
            tx_underrun <= 1'b0;

            // ---------------- word acceptance ----------------
            if (accept) begin
                hold_valid <= 1'b1;
                hold_data  <= in_data;
                hold_nbits <= nbits_eff;
                hold_last  <= in_last;
                if (in_last)
                    closing <= 1'b1;
            end

            case (st)
                // ---------------- idle: wait for a word ----------------
                ST_IDLE: begin
                    tx_en     <= 1'b0;
                    tx_se0    <= 1'b0;
                    last_line <= 1'b1;               // line idles in J
                    if (hold_valid) begin
                        hold_valid <= 1'b0;
                        cur_data   <= hold_data;
                        cur_cnt    <= hold_nbits;
                        cur_last   <= hold_last;
                        spd_q      <= speed;
                        tx_speed   <= speed;
                        tick_cnt   <= div_m1(speed);  // first bit on the next edge
                        eop_cnt    <= 4'd0;
                        st         <= (hold_nbits == 4'd0) ? ST_EOP : ST_RUN;
                    end
                end

                // ---------------- shift data bits ----------------
                ST_RUN: begin
                    if (tick) begin
                        tick_cnt  <= {DIV_W{1'b0}};
                        txd       <= cur_data[0];
                        tx_en     <= 1'b1;
                        tx_se0    <= 1'b0;
                        last_line <= cur_data[0];
                        cur_data  <= {1'b0, cur_data[7:1]};
                        cur_cnt   <= cur_cnt - 4'd1;
                        if (cur_cnt == 4'd1) begin
                            // the last bit of this word is on the line now
                            if (cur_last) begin
                                st      <= ST_EOP;
                                eop_cnt <= 4'd0;
                            end else if (hold_valid) begin
                                hold_valid <= 1'b0;
                                if (hold_nbits == 4'd0) begin
                                    st      <= ST_EOP;       // EOP-only last word
                                    eop_cnt <= 4'd0;
                                end else begin
                                    cur_data <= hold_data;
                                    cur_cnt  <= hold_nbits;
                                    cur_last <= hold_last;
                                end
                            end else begin
                                tx_underrun <= 1'b1;         // no data: abort with EOP
                                st          <= ST_EOP;
                                eop_cnt     <= 4'd0;
                            end
                        end
                    end else begin
                        tick_cnt <= tick_cnt + 1'b1;
                    end
                end

                // ---------------- end of packet ----------------
                ST_EOP: begin
                    if (tick) begin
                        tick_cnt <= {DIV_W{1'b0}};
                        eop_cnt  <= eop_cnt + 4'd1;
                        if (spd_q == SPD_HS) begin
                            if (eop_cnt < 4'd8) begin
                                txd    <= ~last_line;        // transition, then hold
                                tx_en  <= 1'b1;
                                tx_se0 <= 1'b0;
                            end else begin
                                txd     <= 1'b1;
                                tx_en   <= 1'b0;
                                tx_se0  <= 1'b0;
                                st      <= ST_IDLE;
                                closing <= 1'b0;
                                tx_done <= 1'b1;
                            end
                        end else begin
                            case (eop_cnt)
                                4'd0, 4'd1: begin            // SE0, SE0
                                    txd    <= 1'b0;
                                    tx_en  <= 1'b1;
                                    tx_se0 <= 1'b1;
                                end
                                4'd2: begin                  // J
                                    txd    <= 1'b1;
                                    tx_en  <= 1'b1;
                                    tx_se0 <= 1'b0;
                                end
                                default: begin               // release the bus
                                    txd     <= 1'b1;
                                    tx_en   <= 1'b0;
                                    tx_se0  <= 1'b0;
                                    st      <= ST_IDLE;
                                    closing <= 1'b0;
                                    tx_done <= 1'b1;
                                end
                            endcase
                        end
                    end else begin
                        tick_cnt <= tick_cnt + 1'b1;
                    end
                end

                default: st <= ST_IDLE;
            endcase
        end
    end

endmodule
